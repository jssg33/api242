// services/SendTestTrap.js
// Node port of the G4's SendTestTrap (SERVICE-SNMP-LISTENER/sendtesttrap.cs), option 3.
// Like the C# version it sends nothing over the network: it inserts one test Ctssnmpv5 trap record.
// api242's Ctssnmpv5 model embeds the variables; the G4's separate metadata rows go into jsonPayload.

const os = require("os");
const crypto = require("crypto");
const Ctssnmpv5 = require("../models/Ctssnmpv5");

async function execute() {
  const now = new Date();
  const userName = os.userInfo().username;
  const machineName = os.hostname();

  const trap = await Ctssnmpv5.create({
    // Original fields
    trapId: crypto.randomUUID(),
    timestamp: now.toISOString(),
    sourceIp: "127.0.0.1",
    communityString: "public",
    snmpVersion: "3",
    enterpriseOid: "1.3.6.1.4.1.99999",
    genericTrapType: 6,
    specificTrapCode: 1001,
    agentAddress: "127.0.0.1",

    // General
    messageGuid: crypto.randomUUID(),
    receivedUtc: now,
    destinationIp: "127.0.0.1",

    // SNMPv2 / SNMPv3
    trapOid: "1.3.6.1.6.3.1.1.5.3",
    sysUpTime: "12345678",
    engineId: "8000000001020304",
    userName: "ConsoleUser",
    securityLevel: "authPriv",
    authProtocol: "SHA256",
    privacyProtocol: "AES256",
    engineBoots: 10,
    engineTime: 99999,

    // Context
    contextEngineId: "8000000001020304",
    contextName: "ConsoleTrap",

    // Multi-tenant
    correlationId: crypto.randomUUID(),
    tenantId: "TEST",
    region: "LOCAL",

    // Collector
    collectionMethod: "Console",
    collectorVersion: "SendTestTrap 1.0",

    // Payloads (metadata rows from the C# version)
    jsonPayload: JSON.stringify({
      Source: "Console",
      metadata: [
        { category: "Generator", keyName: "Origin", keyValue: "Console" },
        { category: "Generator", keyName: "Service", keyValue: "SendTestTrap" },
        { category: "Environment", keyName: "MachineName", keyValue: machineName },
        { category: "Environment", keyName: "UserName", keyValue: userName }
      ]
    }),
    rawPayload: "Console generated test trap",

    // Location
    lat: "33.9988",
    long: "-81.0348",
    ctsfulllocation: "Columbia SC",

    // VPN
    vpnid: "VPN001",
    vpnid1: "VPNA",
    vpnid2: "VPNB",
    vpnid3: "VPNC",
    vpnid4: "VPND",
    vpnid5: "VPNE",

    // Users
    user1: userName,
    user2: "User2",
    user3: "User3",
    user4: "User4",
    user5: "User5",

    // Additional
    loopbackSourceIp: "127.0.0.1",
    description: "Generated by SendTestTrap",
    severity: "Informational",

    // Enterprise IDs
    userid: "USER001",
    oracleid: "ORA001",
    dynamicsid: "DYN001",
    ncrid: "NCR001",
    inventoryid: "INV001",

    queue: "SNMPQUEUE",
    producttypeid: "NETWORK",
    techassigned: 1,
    repairticket: 99999999,

    variables: [
      { oid: "1.3.6.1.2.1.1.5.0", name: "sysName", value: machineName, dataType: "String", units: null, sequenceOrder: 1 },
      { oid: "1.3.6.1.2.1.1.3.0", name: "sysUpTime", value: "12345678", dataType: "TimeTicks", units: "Milliseconds", sequenceOrder: 2 }
    ]
  });

  console.log(`Created Test Trap ID ${trap._id}`);
  return trap._id;
}

module.exports = { execute };
